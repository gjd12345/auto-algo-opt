"""Render the task-B tables from the measured artifacts.

Writes ``RESULTS_v2.md`` next to the matrix so the report and the numbers in it
cannot drift apart.  Reads ``summary.json`` / ``selectors.json`` (v2) and the
archived v1 outputs for the before/after comparison.

Run:
    python experiments/cvrp_midterm/selection/report_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

OUT = Path(__file__).resolve().parent
V1 = OUT / "v1_20261121"


def markdown_table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join(["---"] * len(headers)) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def pct(value: float) -> str:
    return f"{value * 100:.2f}%"


def main() -> int:
    summary = json.loads((OUT / "summary.json").read_text(encoding="utf-8"))
    selectors = json.loads((OUT / "selectors.json").read_text(encoding="utf-8"))
    design = summary["design"]
    core = summary["portfolios"]["core"]
    extended = summary["portfolios"]["extended"]

    blocks: list[str] = []
    blocks.append("# Task B, revision 2: factorial matrix and selection\n")
    blocks.append(
        "Generated by `report_tables.py` from `summary.json`, `selectors.json` and "
        "`v1_20261121/`. Every number below is reproducible with "
        "`run_matrix.py` then `select.py`.\n"
    )

    blocks.append("## Design\n")
    blocks.append(
        "Three binary factors crossed, demand distribution held fixed at "
        f"U{{{design['demand_range'][0]}, {design['demand_range'][1]}}}: "
        + ", ".join(f"{k} = {'/'.join(v)}" for k, v in design["factors"].items())
        + f". {design['instances_per_cell']} instances per cell, "
        f"{design['customers_per_instance']} customers, {summary['instances']} instances total.\n"
    )
    blocks.append(
        f"Capacity levels are fixed integers: {design['capacity_levels']}. "
        "Capacity ratio (total demand / capacity) therefore varies with the demand "
        "draw but stays near 5.5 under `loose` and 9.0 under `tight`.\n"
    )

    blocks.append("## Rule portfolio, mean objective per instance\n")
    rows = [[name, f"{value:.4f}"]
            for name, value in sorted(summary["portfolio_mean"].items(), key=lambda kv: kv[1])]
    blocks.append(markdown_table(["rule", "mean objective"], rows) + "\n")

    blocks.append("## Oracle headroom\n")
    rows = []
    for label, block in (("core (4 rules)", core), ("extended (6 rules)", extended)):
        rows.append([
            label,
            f"{block['vbs']:.4f}",
            f"{block['sbs']:.4f} ({block['sbs_algorithm']})",
            pct(block["sbs_gap_to_vbs"]),
            ", ".join(f"{k}:{v}" for k, v in sorted(block["oracle_counts"].items())),
        ])
    blocks.append(markdown_table(["portfolio", "VBS", "SBS", "SBS gap to VBS", "oracle wins"], rows) + "\n")
    blocks.append(
        "The two extra rules win no instance at all, so the extended portfolio has "
        "exactly the same VBS and SBS as the core one. The measured headroom is "
        "therefore not an artefact of a thin portfolio.\n"
    )

    blocks.append("## Per cell\n")
    rows = []
    for cell, block in summary["per_cell"].items():
        core_cell = block["core"]
        rows.append([
            cell,
            f"{core_cell['mean_capacity_ratio']:.2f}",
            f"{core_cell['vbs']:.4f}",
            f"{core_cell['sbs']:.4f}",
            core_cell["sbs_algorithm"],
            pct(core_cell["sbs_gap_to_vbs"]),
            ", ".join(f"{k}:{v}" for k, v in sorted(core_cell["oracle_counts"].items())),
        ])
    blocks.append(markdown_table(
        ["cell", "cap ratio", "VBS", "SBS", "SBS rule", "gap", "oracle wins"], rows) + "\n"
    )

    blocks.append("## Selectors (core portfolio)\n")
    rows = []
    for entry in selectors["portfolios"]["core"]["selectors"]:
        rows.append([
            entry["selector"],
            f"{entry['total_objective']:.4f}",
            pct(entry["gap_to_vbs"]),
            pct(entry["mean_regret"]),
            pct(entry["worst_regret"]),
            ", ".join(f"{k}:{v}" for k, v in sorted(entry["picks"].items()) if v),
        ])
    blocks.append(markdown_table(
        ["selector", "total", "gap to VBS", "mean regret", "worst regret", "picks"], rows) + "\n"
    )
    blocks.append(
        "`fixed_best_sbs` picks the single best rule on the whole pool. Its regret is "
        "the price of not knowing the oracle. Every learned selector is compared "
        "against that line, not against the oracle.\n"
    )

    blocks.append("## Leave-one-cell-out details\n")
    loro = next(e for e in selectors["portfolios"]["core"]["selectors"] if e["selector"] == "ridge_loro")
    rows = [[cell, pct(v["gap_to_vbs"]), ", ".join(f"{k}:{v2}" for k, v2 in sorted(v["picks"].items()) if v2)]
            for cell, v in loro["per_held_out_cell"].items()]
    blocks.append(markdown_table(["held-out cell", "gap to VBS", "picks"], rows) + "\n")

    blocks.append("## Main effects of the design factors\n")
    rows = []
    for factor, levels in summary["main_effects"].items():
        for level, block in levels.items():
            means = block["mean_objective"]
            sbs = block["sbs"]["core"]
            vbs = block["vbs"]["core"]
            rows.append([
                factor, level,
                f"{means['nn']:.3f}", f"{means['savings']:.3f}",
                f"{means['dd_load']:.3f}", f"{means['radial']:.3f}",
                f"{vbs:.3f}",
                pct((sbs - vbs) / vbs),
            ])
    blocks.append(markdown_table(
        ["factor", "level", "nn", "savings", "dd_load", "radial", "VBS", "SBS gap"], rows) + "\n")
    blocks.append(
        "Each entry is the mean objective over the 48 instances of that level, so the "
        "levels of one factor are directly comparable; levels of different factors are "
        "not (they average over different instance sets in the other factors).\n"
    )

    blocks.append("## Revision 1 versus revision 2\n")
    v1_summary = json.loads((V1 / "summary.json").read_text(encoding="utf-8"))
    v1_selectors = json.loads((V1 / "selectors.json").read_text(encoding="utf-8"))
    v1_ridge = next(e for e in v1_selectors["selectors"] if e["selector"] == "ridge_loo")
    v1_fixed = next(e for e in v1_selectors["selectors"] if e["selector"] == "fixed_best_sbs")
    ridge_v2 = next(e for e in selectors["portfolios"]["core"]["selectors"] if e["selector"] == "ridge_loo")
    rows = [
        ["instances / cells", "36 / 3", f"{summary['instances']} / {len(summary['per_cell'])}"],
        ["savings rule", "dep+dep-cur (depot leg twice)", "d(i,0)+d(0,j)-d(i,j)"],
        ["factor control", "eccentric cell changed depot, capacity and demands", "three binary factors, demands fixed"],
        ["VBS", f"{v1_summary['vbs_total']:.4f}", f"{core['vbs']:.4f}"],
        ["SBS", f"{v1_summary['sbs_total']:.4f} ({v1_summary['best_fixed']})",
         f"{core['sbs']:.4f} ({core['sbs_algorithm']})"],
        ["SBS gap to VBS", pct(v1_summary["sbs_gap_to_vbs"]), pct(core["sbs_gap_to_vbs"])],
        ["ridge LOO vs fixed", f"{pct(v1_ridge['gap_to_vbs'])} vs {pct(v1_fixed['gap_to_vbs'])}",
         f"{pct(ridge_v2['gap_to_vbs'])} vs {pct(core['sbs_gap_to_vbs'])}"],
        ["ridge LOO verdict", "beats fixed by "
         f"{(v1_fixed['gap_to_vbs'] - v1_ridge['gap_to_vbs']) * 100:.2f} pp",
         "loses to fixed by "
         f"{(ridge_v2['gap_to_vbs'] - core['sbs_gap_to_vbs']) * 100:.2f} pp"],
    ]
    blocks.append(markdown_table(["quantity", "revision 1", "revision 2"], rows) + "\n")

    blocks.append("## Rule self-check\n")
    check = summary["rule_check"]
    blocks.append(
        f"- ranking score: `{check['rule']}`\n"
        f"- cases checked against a brute-force reading: {check['cases_checked']}\n"
        f"- every saving is exactly zero while standing at the depot: {check['all_savings_zero_at_depot']}\n"
        f"- tie-break at the depot: {check['tie_break_at_depot']}\n"
        f"- is full Clarke-Wright: {check['is_full_clarke_wright']}\n"
    )

    text = "\n".join(blocks)
    (OUT / "RESULTS_v2.md").write_text(text, encoding="utf-8", newline="\n")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
