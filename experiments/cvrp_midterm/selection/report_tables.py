"""Render the task-B tables from the measured artifacts.

Writes ``RESULTS_v3.md`` next to the matrix so the report and the numbers in it
cannot drift apart.  Reads ``summary.json`` / ``selectors.json`` (v3: frozen C in
the pool, pairwise selectors) plus the archived v2 outputs for the before/after
comparison.

Run:
    python experiments/cvrp_midterm/selection/report_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

OUT = Path(__file__).resolve().parent
V2 = OUT / "v2_20261121"

PORTFOLIO_LABEL = {
    "core": "core (4 rules)",
    "with_c": "core + frozen C",
    "extended": "extended (6 rules)",
    "extended_c": "extended + frozen C",
}


def markdown_table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join(["---"] * len(headers)) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def pct(value: float) -> str:
    return f"{value * 100:.2f}%"


def oracle(block: dict) -> str:
    return ", ".join(f"{k}:{v}" for k, v in sorted(block["oracle_counts"].items()))


def main() -> int:
    summary = json.loads((OUT / "summary.json").read_text(encoding="utf-8"))
    selectors = json.loads((OUT / "selectors.json").read_text(encoding="utf-8"))
    design = summary["design"]
    portfolios = summary["portfolios"]
    core = portfolios["core"]
    with_c = portfolios["with_c"]

    blocks: list[str] = []
    blocks.append("# Task B, revision 3: frozen C in the pool, pairwise selection\n")
    blocks.append(
        "Generated by `report_tables.py` from `summary.json`, `selectors.json` and the "
        "archived v2 outputs. Reproduce with `run_matrix.py` then `select.py`.\n"
    )

    blocks.append("## Design\n")
    blocks.append(
        "Three binary factors crossed, demand distribution held fixed at "
        f"U{{{design['demand_range'][0]}, {design['demand_range'][1]}}}: "
        + ", ".join(f"{k} = {'/'.join(v)}" for k, v in design["factors"].items())
        + f". {design['instances_per_cell']} instances per cell, "
        f"{design['customers_per_instance']} customers, {summary['instances']} instances total.\n"
    )
    blocks.append(
        f"Capacity levels are fixed integers: {design['capacity_levels']}. "
        "Every factor moves one thing only, so a main effect is attributable.\n"
    )
    blocks.append(
        f"The frozen pointwise rule `C` is added to the pool verbatim from "
        f"`{design['frozen_member']['path']}` (sha256 `{design['frozen_member']['sha256'][:16]}…`, "
        f"{design['frozen_member']['bytes']} bytes, `edited_here` = "
        f"{design['frozen_member']['edited_here']}); the matrix builder refuses to run if the "
        "file's hash changes.\n"
    )

    blocks.append("## Rule portfolio, mean objective per instance\n")
    rows = [[name, f"{value:.4f}"]
            for name, value in sorted(summary["portfolio_mean"].items(), key=lambda kv: kv[1])]
    blocks.append(markdown_table(["rule", "mean objective"], rows) + "\n")

    blocks.append("## Oracle headroom per portfolio\n")
    rows = []
    for key in ("core", "with_c", "extended", "extended_c"):
        block = portfolios[key]
        rows.append([
            PORTFOLIO_LABEL[key],
            f"{block['vbs']:.4f}",
            f"{block['sbs']:.4f} ({block['sbs_algorithm']})",
            pct(block["sbs_gap_to_vbs"]),
            f"{block['headroom']:.4f}",
            oracle(block),
        ])
    blocks.append(markdown_table(
        ["portfolio", "VBS", "SBS", "SBS gap to VBS", "headroom (SBS-VBS)", "oracle wins"], rows) + "\n")
    blocks.append(
        "`isolate` and `load_fill` win nothing, so `extended` reproduces `core` exactly and "
        "`extended_c` reproduces `with_c`; the measurable headroom is not an artefact of a "
        "thin portfolio. Adding `C` lowers the VBS (a strictly better rule exists on some "
        "instances) but leaves the SBS untouched: no single fixed rule is beaten by it often "
        "enough to change the best fixed choice.\n"
    )

    blocks.append("## Frozen C against the incumbent rules, pairwise\n")
    rows = []
    for key in ("c_vs_savings", "c_vs_nn", "c_vs_dd_load"):
        pair = summary["pairwise"][key]
        total = pair["a_better"] + pair["equal"] + pair["b_better"]
        rows.append([
            f"{pair['a']} vs {pair['b']}",
            f"{pair['a_better']}/{total}",
            f"{pair['equal']}",
            f"{pair['b_better']}/{total}",
            pct(pair["mean_relative_delta"]),
            pct(pair["median_relative_delta"]),
        ])
    blocks.append(markdown_table(
        ["pair", "first wins", "ties", "second wins", "mean rel. delta", "median rel. delta"], rows) + "\n")
    blocks.append(
        "Relative delta is measured on the second rule's objective, positive meaning the "
        "first rule is worse there. `C` is clearly worse than `savings` overall yet still "
        "wins 12 instances outright — which is exactly why it belongs in a portfolio and "
        "not in a single-rule submission.\n"
    )

    blocks.append("## Per cell (extended + C)\n")
    rows = []
    for cell, block in summary["per_cell"].items():
        cell_block = block["extended_c"]
        rows.append([
            cell,
            f"{cell_block['mean_capacity_ratio']:.2f}",
            f"{cell_block['vbs']:.4f}",
            f"{cell_block['sbs']:.4f}",
            cell_block["sbs_algorithm"],
            pct(cell_block["sbs_gap_to_vbs"]),
            oracle(cell_block),
        ])
    blocks.append(markdown_table(
        ["cell", "cap ratio", "VBS", "SBS", "SBS rule", "gap", "oracle wins"], rows) + "\n")

    blocks.append("## Selectors, extended + C portfolio\n")
    entries = selectors["portfolios"]["extended_c"]["selectors"]
    rows = []
    for entry in entries:
        rows.append([
            entry["selector"],
            f"{entry['total_objective']:.4f}",
            pct(entry["gap_to_vbs"]),
            pct(entry["gain_vs_fixed"]),
            pct(entry["mean_regret"]),
            pct(entry["worst_regret"]),
            ", ".join(f"{k}:{v}" for k, v in sorted(entry["picks"].items()) if v),
        ])
    blocks.append(markdown_table(
        ["selector", "total", "gap to VBS", "gain vs fixed", "mean regret", "worst regret", "picks"],
        rows) + "\n")
    blocks.append(
        "`fixed_best_sbs` is the line to beat, not the oracle. A negative gain means the "
        "selector did worse than always submitting the single best rule; every learned "
        "selector here is negative, including the pairwise one.\n"
    )

    blocks.append("## Selector summary across portfolios\n")
    rows = []
    for key in ("core", "with_c", "extended_c"):
        for entry in selectors["portfolios"][key]["selectors"]:
            rows.append([PORTFOLIO_LABEL[key], entry["selector"],
                         pct(entry["gap_to_vbs"]), pct(entry["gain_vs_fixed"])])
    blocks.append(markdown_table(["portfolio", "selector", "gap to VBS", "gain vs fixed"], rows) + "\n")

    blocks.append("## Leave-one-cell-out details (extended + C)\n")
    loro = next(e for e in entries if e["selector"] == "ridge_loro")
    pairs = next(e for e in entries if e["selector"] == "pairwise_loro")
    by_cell = {}
    for name, entry in (("ridge", loro), ("pairwise", pairs)):
        for cell, value in entry["per_held_out_cell"].items():
            by_cell.setdefault(cell, {})[name] = value
    rows = []
    for cell in sorted(by_cell, key=lambda c: by_cell[c]["ridge"]["gap_to_vbs"], reverse=True):
        row = [cell]
        for name in ("ridge", "pairwise"):
            value = by_cell[cell].get(name)
            row += [pct(value["gap_to_vbs"]),
                    ", ".join(f"{k}:{v}" for k, v in sorted(value["picks"].items()) if v)] if value else ["n/a", "n/a"]
        rows.append(row)
    blocks.append(markdown_table(
        ["held-out cell", "ridge gap", "ridge picks", "pairwise gap", "pairwise picks"], rows) + "\n")

    blocks.append("## Main effects of the design factors\n")
    rules = ["nn", "savings", "dd_load", "radial", "c"]
    rows = []
    for factor, levels in summary["main_effects"].items():
        for level, block in levels.items():
            means = block["mean_objective"]
            rows.append([factor, level]
                        + [f"{means[r]:.3f}" for r in rules]
                        + [f"{block['vbs']['extended_c']:.3f}",
                           pct((block["sbs"]["extended_c"] - block["vbs"]["extended_c"])
                               / block["vbs"]["extended_c"])])
    blocks.append(markdown_table(
        ["factor", "level"] + rules + ["VBS", "SBS gap"], rows) + "\n")
    blocks.append(
        "Each entry averages the 48 instances of that level, so levels of one factor are "
        "comparable; levels of different factors are not. `C` reacts to the factors in the "
        "same direction as `savings` — both prefer uniform, centred and loose instances — "
        "so the two rules overlap on the easy cases rather than covering each other.\n"
    )

    blocks.append("## Revision 2 versus revision 3\n")
    v2_summary = json.loads((V2 / "summary.json").read_text(encoding="utf-8"))
    v2_selectors = json.loads((V2 / "selectors.json").read_text(encoding="utf-8"))
    v2_core = v2_summary["portfolios"]["core"]
    v2_best = next(e for e in v2_selectors["portfolios"]["core"]["selectors"]
                   if e["selector"] == "ridge_loo")
    v3_ridge = next(e for e in entries if e["selector"] == "ridge_loo")
    v3_pair = next(e for e in entries if e["selector"] == "pairwise_loo")
    rows = [
        ["rules in pool", "4 (nn, savings, dd_load, radial)", "5 (+ frozen C)"],
        ["instances", f"{v2_summary['instances']}", f"{summary['instances']}"],
        ["VBS", f"{v2_core['vbs']:.4f}", f"{with_c['vbs']:.4f}"],
        ["SBS", f"{v2_core['sbs']:.4f} ({v2_core['sbs_algorithm']})",
         f"{with_c['sbs']:.4f} ({with_c['sbs_algorithm']})"],
        ["SBS gap to VBS", pct(v2_core["sbs_gap_to_vbs"]), pct(with_c["sbs_gap_to_vbs"])],
        ["best learned selector", f"ridge LOO {pct(v2_best['gap_to_vbs'])}",
         f"ridge LOO {pct(v3_ridge['gap_to_vbs'])}"],
        ["that selector vs fixed", f"{pct(v2_best['gap_to_vbs'] - v2_core['sbs_gap_to_vbs'])} worse",
         f"{pct(v3_ridge['gap_to_vbs'] - with_c['sbs_gap_to_vbs'])} worse"],
        ["pairwise LOO", "not implemented", pct(v3_pair["gap_to_vbs"])],
        ["verdict", "no learned selector beats fixed",
         "still none, with a strictly larger pool and a pairwise learner"],
    ]
    blocks.append(markdown_table(["quantity", "revision 2", "revision 3"], rows) + "\n")

    blocks.append("## Rule self-check\n")
    check = summary["rule_check"]
    blocks.append(
        f"- ranking score: `{check['rule']}`\n"
        f"- cases checked against a brute-force reading: {check['cases_checked']}\n"
        f"- every saving is exactly zero while standing at the depot: {check['all_savings_zero_at_depot']}\n"
        f"- tie-break at the depot: {check['tie_break_at_depot']}\n"
        f"- is full Clarke-Wright: {check['is_full_clarke_wright']}\n"
        f"- frozen C untouched: sha256 `{design['frozen_member']['sha256']}`\n"
    )

    text = "\n".join(blocks)
    (OUT / "RESULTS_v3.md").write_text(text, encoding="utf-8", newline="\n")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
