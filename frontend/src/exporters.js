/* Publication-grade asset exporters: SVG, 300 DPI PNG, LaTeX booktabs .tex, CSV, JSON.
 * 100% client-side offline export using exact release data.
 */
(function () {
  "use strict";

  function triggerDownload(filename, mimeType, content) {
    const blob = content instanceof Blob ? content : new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    setTimeout(function () {
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }, 100);
  }

  function serializeSvg(svgEl) {
    if (!svgEl) return null;
    const clone = svgEl.cloneNode(true);
    clone.setAttribute("xmlns", "http://www.w3.org/2000/svg");
    const vb = clone.getAttribute("viewBox");
    let w = Number(clone.getAttribute("width")) || 0;
    let h = Number(clone.getAttribute("height")) || 0;
    if ((!w || !h) && vb) {
      const parts = vb.trim().split(/[\s,]+/).map(Number);
      if (parts.length === 4) {
        w = parts[2];
        h = parts[3];
      }
    }
    if (!w) w = svgEl.clientWidth || 720;
    if (!h) h = svgEl.clientHeight || 420;
    clone.setAttribute("width", String(w));
    clone.setAttribute("height", String(h));
    return {
      xml: '<?xml version="1.0" encoding="UTF-8"?>\n' + new XMLSerializer().serializeToString(clone),
      width: w,
      height: h
    };
  }

  function exportSvg(svgEl, filename) {
    const res = serializeSvg(svgEl);
    if (!res) return false;
    triggerDownload(filename || "figure.svg", "image/svg+xml;charset=utf-8", res.xml);
    return true;
  }

  function exportPng300Dpi(svgEl, filename) {
    const res = serializeSvg(svgEl);
    if (!res) return false;
    const scale = 300 / 96; // 3.125x rasterization for 300 DPI print clarity
    const img = new Image();
    const svgBlob = new Blob([res.xml], { type: "image/svg+xml;charset=utf-8" });
    const url = URL.createObjectURL(svgBlob);
    img.onload = function () {
      const canvas = document.createElement("canvas");
      canvas.width = Math.round(res.width * scale);
      canvas.height = Math.round(res.height * scale);
      const ctx = canvas.getContext("2d");
      ctx.fillStyle = "#fffefa";
      ctx.fillRect(0, 0, canvas.width, canvas.height);
      ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
      URL.revokeObjectURL(url);
      canvas.toBlob(function (pngBlob) {
        if (pngBlob) triggerDownload(filename || "figure_300dpi.png", "image/png", pngBlob);
      }, "image/png");
    };
    img.onerror = function () {
      URL.revokeObjectURL(url);
    };
    img.src = url;
    return true;
  }

  function latexEscape(text) {
    return String(text || "")
      .replace(/\\/g, "\\textbackslash{}")
      .replace(/([_%&#${}])/g, "\\$1");
  }

  function generateLatexLocalTable(core, suiteId, scope) {
    const L = window.WB_LABELS;
    const suite = L.getSuite(core, suiteId);
    const sum = L.getSuiteSummary(core, suiteId);
    if (!suite || !sum) return "% Suite summary unavailable";

    const useCommon = scope === "common_completed" && sum.common_completed_count;
    const commonN = sum.common_completed_count || suite.instance_count;
    const rows = Object.keys(sum.algorithms || {}).map(function (aid) {
      const stats = L.getAlgStats(sum, aid, scope);
      return { aid: aid, stats: stats, allStats: L.getAlgStats(sum, aid, "overall") };
    }).filter(function (r) { return Boolean(r.stats); });

    rows.sort(function (a, b) {
      const ga = a.stats.mean_rel_gap !== null && a.stats.mean_rel_gap !== undefined ? a.stats.mean_rel_gap : 999;
      const gb = b.stats.mean_rel_gap !== null && b.stats.mean_rel_gap !== undefined ? b.stats.mean_rel_gap : 999;
      return ga - gb;
    });

    const scopeDesc = useCommon
      ? ("Common completed intersection $N_{\\text{common}}=" + commonN + "$ / " + suite.instance_count)
      : ("Per-algorithm completed samples (out of $N=" + suite.instance_count + "$)");

    const lines = [
      "% Auto-generated by CO-Workbench (" + (core.release_id || "") + ") — local_recomputed track ONLY",
      "\\begin{table}[t]",
      "  \\centering",
      "  \\caption{" + latexEscape(L.suiteTitle(suite)) + " (\\texttt{" + latexEscape(suiteId) + "}, " + scopeDesc + ", Budget " + (sum.budget_ms || 500) + "\\,ms)}",
      "  \\begin{tabular}{llrrrr}",
      "    \\toprule",
      "    Algorithm & Paradigm & ok/$N$ & Mean Obj. & Mean Gap (\\%) & $P_{50}/P_{95}$ Solve (ms) \\\\",
      "    \\midrule"
    ];

    rows.forEach(function (r) {
      const a = L.getAlg(core, r.aid);
      const st = r.stats;
      const allSt = r.allStats || st;
      const okStr = allSt.ok_count + "/" + allSt.n_instances;
      const objStr = st.mean_tour_length !== null && st.mean_tour_length !== undefined ? Number(st.mean_tour_length).toFixed(4) : "--";
      const gapStr = st.mean_rel_gap !== null && st.mean_rel_gap !== undefined ? (Number(st.mean_rel_gap) * 100).toFixed(2) + "\\%" : "--";
      const msStr = (st.solve_ms_p50 !== null && st.solve_ms_p50 !== undefined ? Number(st.solve_ms_p50).toFixed(2) : "--") +
        " / " + (st.solve_ms_p95 !== null && st.solve_ms_p95 !== undefined ? Number(st.solve_ms_p95).toFixed(2) : "--");
      lines.push(
        "    \\texttt{" + latexEscape(r.aid) + "} & " +
        latexEscape((a && a.paradigm) || "") + " & " +
        okStr + " & " + objStr + " & " + gapStr + " & " + msStr + " \\\\"
      );
    });

    lines.push(
      "    \\bottomrule",
      "  \\end{tabular}",
      "  \\vspace{2pt}",
      "  \\footnotesize{\\emph{Notes:} Mode=\\texttt{local\\_recomputed}; Ref=\\texttt{" + latexEscape(sum.reference_kind || "") + "}; Dist=\\texttt{" + latexEscape(sum.distance_convention || "") + "}. Separate from paper-reported tables.}",
      "\\end{table}"
    );
    return lines.join("\n");
  }

  function exportCsv(rows, columns, filename) {
    if (!rows || !rows.length) return false;
    const header = columns.map(function (c) { return '"' + String(c).replace(/"/g, '""') + '"'; }).join(",");
    const body = rows.map(function (r) {
      return columns.map(function (c) {
        const v = r[c];
        if (v === null || v === undefined) return "";
        return '"' + String(v).replace(/"/g, '""') + '"';
      }).join(",");
    }).join("\n");
    triggerDownload(filename || "records.csv", "text/csv;charset=utf-8", "\uFEFF" + header + "\n" + body);
    return true;
  }

  function exportJson(payload, filename) {
    triggerDownload(filename || "records.json", "application/json;charset=utf-8", JSON.stringify(payload, null, 2));
    return true;
  }

  window.WB_EXPORT = {
    exportSvg: exportSvg,
    exportPng300Dpi: exportPng300Dpi,
    generateLatexLocalTable: generateLatexLocalTable,
    exportCsv: exportCsv,
    exportJson: exportJson,
    downloadText: function (filename, text) {
      triggerDownload(filename, "text/plain;charset=utf-8", text);
    }
  };
})();
