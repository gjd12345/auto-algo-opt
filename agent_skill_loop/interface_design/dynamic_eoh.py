"""DynamicInterfaceProblem (eoh.BaseProblem subclass) and Milestone 2 EoH runner (Task 2A-4).

Zero edits to ``eoh_frozen/``: directly subclasses ``eoh.BaseProblem`` and drives the
pinned upstream ``eoh.eoh.eoh.EOH`` engine with either:
  - live LLM via ``eoh_frozen.llm_bridge.OpenAIPathBridge`` + ``RequestBudget``; or
  - deterministic local mock HTTP server for fast, reproducible offline tests.

Every candidate hook generated by EoH is evaluated through the exact same AST capability
whitelist, registered template, and M1 ``verify_cvrp_solution`` verifier used by
``InterfaceValidator`` and ``run_frozen_workbench_bundle``.
"""

