def _summarize_request_log(request_log: Path) -> dict[str, Any]:
    counts_by_purpose: dict[str, int] = {}
    prompt_tokens = 0
    completion_tokens = 0
    total_tokens = 0
    completed_requests = 0
    attempted_requests = 0
    if not request_log.is_file():
        return {
            "attempted_requests": 0,
            "completed_requests": 0,
            "by_purpose": {},
            "prompt_tokens": 0,
            "completion_tokens": 0,
            "total_tokens": 0,
        }
    for line in request_log.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        state = row.get("state")
        if state == "reserved":
            attempted_requests += 1
        if state is None or state in {"complete", "completed", "ok"}:
            purpose = str(row.get("purpose") or "unknown")
            counts_by_purpose[purpose] = counts_by_purpose.get(purpose, 0) + 1
            completed_requests += 1
            usage = row.get("usage") if isinstance(row.get("usage"), dict) else {}
            in_tok = int(row.get("input_tokens") or usage.get("prompt_tokens") or 0)
            out_tok = int(row.get("output_tokens") or usage.get("completion_tokens") or 0)
            prompt_tokens += in_tok
            completion_tokens += out_tok
            total_tokens += int(usage.get("total_tokens") or (in_tok + out_tok))
    return {
        "attempted_requests": max(attempted_requests, completed_requests),
        "completed_requests": completed_requests,
        "by_purpose": counts_by_purpose,
        "prompt_tokens": prompt_tokens,
        "completion_tokens": completion_tokens,
        "total_tokens": total_tokens,
    }


