def _utc_now() -> str:
    return _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


class DynamicInterfaceProblem(BaseProblem):
    """Official EoH ``BaseProblem`` bound to a validated Milestone 2 ``InterfaceDesign``."""

    def __init__(
        self,
        *,
        design: InterfaceDesign,
        instances: Sequence[Mapping[str, Any]],
        suite_id: str,
        suite_hash: str | None = None,
        distance_convention: str = "euc_2d_float",
        vehicle_limit_policy: str = "unconstrained",
        candidate_timeout_s: float = 20.0,
        instance_time_budget_ms: float = 500.0,
        evaluation_log: str | Path | None = None,
        round_context: str | None = None,
        n_processes: int = 1,
    ) -> None:
        assert_suite_not_m2_blind(suite_id)
        # EoH outer process timeout receives a margin above our inner subprocess timeout
        super().__init__(timeout=max(5, int(candidate_timeout_s) + 5), n_processes=n_processes)
        self.design = design
        self.tpl = get_template_spec(design.template_id, design.template_version)
        self.instances = [dict(inst) for inst in instances]
        self.suite_id = str(suite_id)
        self.suite_hash = suite_hash
        self.distance_convention = str(distance_convention)
        self.vehicle_limit_policy = str(vehicle_limit_policy)
        self.candidate_timeout_s = float(candidate_timeout_s)
        self.instance_time_budget_ms = float(instance_time_budget_ms)
        self.evaluation_log = str(evaluation_log) if evaluation_log is not None else None
        self.round_context = round_context.strip() if isinstance(round_context, str) and round_context.strip() else None
        self._log_lock = threading.Lock()

    def __getstate__(self) -> dict[str, Any]:
        """Keep problem picklable for EoH's spawn-based evaluation workers."""
        state = self.__dict__.copy()
        state.pop("_log_lock", None)
        state.pop("tpl", None)
        return state

    def __setstate__(self, state: dict[str, Any]) -> None:
        self.__dict__.update(state)
        self.tpl = get_template_spec(self.design.template_id, self.design.template_version)
        self._log_lock = threading.Lock()

    @property
    def template_program(self) -> str:
        return self.tpl.default_template_program

    @property
    def task_description(self) -> str:
        contract = capability_contract_dict(
            hook_name=self.design.hook_name,
            hook_signature=self.design.hook_signature,
            template_id=self.design.template_id,
            template_version=self.design.template_version,
        )
        text = (
            self.design.hook_task_description
            + "\n\nEVALUATOR CAPABILITY CONTRACT (machine-derived; mandatory):\n"
            + json.dumps(contract, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
        )
        if self.round_context:
            text += "\n\n" + self.round_context
        return text

    def evaluate(self, code_string: str) -> float | None:
        resp = self.evaluate_detailed(code_string)
        if not resp.get("valid") or resp.get("objective") is None:
            return None
        return float(resp["objective"])

    def evaluate_program(self, program_str: str, callable_func: Any = None) -> float | None:
        return self.evaluate(program_str)

    def evaluate_detailed(self, code_string: str) -> dict[str, Any]:
        evaluator = DynamicSubprocessEvaluator(candidate_timeout_s=self.candidate_timeout_s)
        resp = evaluator.evaluate(
            template_id=self.design.template_id,
            template_version=self.design.template_version,
            hook_code=str(code_string),
            instances=self.instances,
            postprocess_mode=self.design.postprocess_mode,
            template_options=self.design.template_options,
            distance_convention=self.distance_convention,
            vehicle_limit_policy=self.vehicle_limit_policy,
            instance_time_budget_ms=self.instance_time_budget_ms,
        )
        self._append_eval_log(str(code_string), resp)
        return resp

    def _append_eval_log(self, code_string: str, resp: Mapping[str, Any]) -> None:
        if not self.evaluation_log:
            return
        records = resp.get("records") or []
        outcome_counts: dict[str, int] = {}
        for r in records:
            oc = str(r.get("outcome_class", "timeout_or_infeasible"))
            outcome_counts[oc] = outcome_counts.get(oc, 0) + 1
        row = {
            "timestamp": _utc_now(),
            "evaluation_id": uuid.uuid4().hex,
            "pid": os.getpid(),
            "design_id": self.design.design_id,
            "design_sha256": self.design.design_sha256,
            "template_id": self.design.template_id,
            "template_version": self.design.template_version,
            "template_source_sha256": self.tpl.template_source_sha256,
            "postprocess_mode": self.design.postprocess_mode,
            "suite_id": self.suite_id,
            "suite_hash": self.suite_hash,
            "hook_code": code_string,
            "hook_code_sha256": sha256_text(code_string),
            "valid": bool(resp.get("valid")),
            "objective": resp.get("objective"),
            "instance_objectives": resp.get("instance_objectives", []),
            "error_code": resp.get("error_code"),
            "error_detail": resp.get("error_detail"),
            "outcome_counts": outcome_counts,
            "worker_wall_ms": resp.get("worker_wall_ms"),
            "subprocess_overhead_ms": resp.get("subprocess_overhead_ms"),
        }
        path = Path(self.evaluation_log)
        path.parent.mkdir(parents=True, exist_ok=True)
        with self._log_lock:
            with path.open("a", encoding="utf-8") as handle:
                handle.write(json.dumps(row, ensure_ascii=False, allow_nan=False) + "\n")
                handle.flush()


class MockEoHLLMServer:
    """Deterministic local HTTP LLM server for offline EoH integration tests."""

    def __init__(self, responses: Sequence[str], *, request_log: Path | None = None) -> None:
        self.responses = list(responses)
        self.request_log = Path(request_log) if request_log is not None else None
        self._lock = threading.Lock()
        self._idx = 0
        self.call_count = 0
        self._server: ThreadingHTTPServer | None = None

    @property
    def local_url(self) -> str:
        if self._server is None:
            raise RuntimeError("mock_server_not_started")
        port = self._server.server_address[1]
        return f"http://127.0.0.1:{port}/completions"

    def start(self) -> str:
        srv_owner = self

        class Handler(BaseHTTPRequestHandler):
            def do_POST(self) -> None:  # noqa: N802
                length = int(self.headers.get("Content-Length") or 0)
                raw = self.rfile.read(length) if length else b"{}"
                payload = json.loads(raw.decode("utf-8"))
                prompt = str(payload.get("prompt") or "")
                with srv_owner._lock:
                    srv_owner.call_count += 1
                    req_idx = srv_owner.call_count
                    if prompt.strip() == "1+1=?":
                        text = "2"
                    else:
                        text = srv_owner.responses[srv_owner._idx % len(srv_owner.responses)]
                        srv_owner._idx += 1
                    if srv_owner.request_log is not None:
                        srv_owner.request_log.parent.mkdir(parents=True, exist_ok=True)
                        with srv_owner.request_log.open("a", encoding="utf-8") as h:
                            h.write(json.dumps({
                                "request_index": req_idx,
                                "mode": "deterministic_mock",
                                "purpose": "eoh_probe" if prompt.strip() == "1+1=?" else "eoh_generation",
                                "prompt_chars": len(prompt),
                                "response_chars": len(text),
                            }, ensure_ascii=False) + "\n")
                body = json.dumps({"content": [text], "request_index": req_idx}).encode("utf-8")
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)

            def log_message(self, format: str, *args: Any) -> None:  # noqa: A003
                return

        self._server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        t = threading.Thread(target=lambda: self._server.serve_forever(poll_interval=0.05), daemon=True)
        t.start()
        return self.local_url

    def stop(self) -> None:
        if self._server is not None:
            self._server.shutdown()
            self._server.server_close()
            self._server = None


